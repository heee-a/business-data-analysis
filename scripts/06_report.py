def _render_block(doc, kind: str, payload) -> None:
    if kind == "p":
        render_text_paragraph(doc, payload)
    elif kind == "img":
        name, caption = payload
        # name 含 "/" 时按 outputs/ 下相对路径解析（如 dashboard_screenshots/大屏演示_四标签拼图）
        if "/" in name:
            img_path = cfg.OUT_DIR / f"{name}.png"
        else:
            img_path = cfg.FIG_DIR / f"{name}.png"
        add_image(doc, img_path, caption)
    elif kind == "table":
        add_table(doc, payload["header"], payload["rows"], payload.get("caption", ""))
    elif kind == "bullets":
        add_bullets(doc, payload)
    elif kind == "h3":
        add_heading(doc, payload, 3)
    elif kind == "code":
        _add_code(doc, payload)


def _add_code(doc, lines: list[str]) -> None:
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.15
    pf.space_after = Pt(8)
    pf.left_indent = Pt(18)
    for i, ln in enumerate(lines):
        if i:
            p.add_run("\n")
        r = p.add_run(ln)
        set_cn_font(r, "Consolas", size=9)


