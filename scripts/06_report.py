def set_cn_font(run, cn: str = "宋体", en: str = "Times New Roman", size: float | None = None):
    """同时设置中文字体与西文字体，避免中文变方块/西文被中文字体渲染。"""
    run.font.name = en
    run.font.color.rgb = RGBColor(0, 0, 0)
    if size:
        run.font.size = Pt(size)
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rf)
    rf.set(qn("w:eastAsia"), cn)
    rf.set(qn("w:ascii"), en)
    rf.set(qn("w:hAnsi"), en)


def add_para(doc, text: str, *, size: float = 12, cn: str = "宋体",
             bold: bool = False, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
             indent: bool = True, space_after: float = 4,
             line_spacing: float = 1.5) -> None:
    p = doc.add_paragraph()
    p.alignment = align
    pf = p.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(0)
    if indent:
        pf.first_line_indent = Pt(size * 2)
    r = p.add_run(text)
    r.bold = bold
    set_cn_font(r, cn, size=size)
    return p


def add_heading(doc, text: str, level: int = 1) -> None:
    sizes = {1: 14, 2: 12, 3: 12}
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(8 if level == 1 else 5)
    pf.space_after = Pt(4)
    r = p.add_run(text)
    r.bold = True
    set_cn_font(r, "黑体", size=sizes.get(level, 12))
    return p


def add_table(doc, header: list[str], rows: list[list[str]], caption: str = "") -> None:
    if caption:
        cp = doc.add_paragraph()
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        cp.paragraph_format.space_after = Pt(2)
        r = cp.add_run(caption)
        set_cn_font(r, "黑体", size=10.5)

    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(header):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(h)
        r.bold = True
        set_cn_font(r, "黑体", size=10)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER if i == 0 or len(header) == 2 else WD_ALIGN_PARAGRAPH.LEFT
            p.paragraph_format.space_after = Pt(1)
            r = p.add_run(str(v))
            set_cn_font(r, size=10)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def add_image(doc, path: Path, caption: str, width_cm: float = 15.0) -> None:
    if not path.exists():
        iou.log(f"  图缺失，跳过：{path.name}", "WARN")
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(1)
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cp.paragraph_format.space_after = Pt(8)
    r = cp.add_run(caption)
    set_cn_font(r, size=10.5)


def add_bullets(doc, items: list[str]) -> None:
    for it in items:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.line_spacing = 1.5
        pf.space_after = Pt(3)
        pf.left_indent = Pt(24)
        pf.first_line_indent = Pt(-12)
        # 支持 **加粗** 片段
        segs = it.split("**")
        for i, seg in enumerate(segs):
            if not seg:
                continue
            r = p.add_run(seg)
            set_cn_font(r, size=12)
            r.bold = (i % 2 == 1)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def render_text_paragraph(doc, text: str) -> None:
    """渲染正文，支持 **加粗** 内联标记。"""
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(4)
    pf.first_line_indent = Pt(24)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run(seg)
        set_cn_font(r, size=12)
        r.bold = (i % 2 == 1)


